/// 中文名的英文译名；两张表都查不到就原样返回，保证不会显示空白。
String nameEn(String zh) => kFestivalEn[zh] ?? kJieQiEn[zh] ?? zh;

/// 当前语言下的显示名：中文界面原样返回，英文界面查译名表。
///
/// 农历日（初一）、干支、生肖这类文化数据不在译名表里，查不到自然回退中文，
/// 与日历页「文化数据保持中文原样」的既定约定一致。
String nameLabel(String zh, AppLocalizations l10n) =>
    l10n.localeName.startsWith('en') ? nameEn(zh) : zh;

/// 「节气」行的展示文本：空值给本地化的「无」，有值查译名。
String jieQiText(String jieQi, AppLocalizations l10n) =>
    jieQi.isEmpty ? l10n.commonNone : nameLabel(jieQi, l10n);

/// 「节日」行的展示文本：空值给「无」，多个名字按语言习惯连接。
String festivalNamesText(List<String> names, AppLocalizations l10n) =>
    names.isEmpty
        ? l10n.commonNone
        : names
            .map((n) => nameLabel(n, l10n))
            .join(l10n.localeName.startsWith('en') ? ', ' : '、');
